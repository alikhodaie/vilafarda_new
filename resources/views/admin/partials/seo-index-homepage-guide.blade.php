    <h6 class="alert-heading mb-2">
        <span class="fas fa-home ms-1"></span>
        راهنمای سئو — صفحه اصلی (دسکتاپ و موبایل)
    </h6>
    <p class="mb-2 small">
        موارد زیر روی صفحه اصلی <strong>به‌صورت خودکار</strong> اعمال شده‌اند. شما در ادمین فقط متن‌ها و تصاویر را پر کنید.
    </p>
    <ul class="mb-0 small ps-3">
        <li class="mb-2">
            <strong>عنوان سئو (Title):</strong> فیلد «صفحه اصلی» در بخش عنوان صفحات.
            اگر خالی باشد از «عنوان صفحه» در تنظیمات صفحه اصلی استفاده می‌شود.
            مثال: <code>اجاره ویلا و سوئیت در شمال</code>
        </li>
        <li class="mb-2">
            <strong>توضیح متا (Description):</strong> فیلد «صفحه اصلی» در بخش توضیح متا.
            اگر خالی باشد از «توضیح بنر» صفحه اصلی استفاده می‌شود.
            جملهٔ دعوت به عمل + شهر/خدمت اصلی، حداکثر ۱۵۰ کاراکتر.
        </li>
        <li class="mb-2">
            <strong>تگ H1:</strong> در بنر ویدیو از «عنوان بنر» استفاده می‌شود؛ در بنر اسلایدر یک H1 مخفی (برای گوگل) از همان عنوان ساخته می‌شود.
            عنوان بنر را در <em>تنظیمات → صفحه اصلی</em> واضح و شامل کلمه کلیدی بنویسید.
        </li>
        <li class="mb-2">
            <strong>ساختار عناوین:</strong> هر بخش (اقتصادی، محبوب، نقشه، نظرات، مقالات) با <code>h2</code> مشخص شده است — عناوین بخش‌ها در تنظیمات صفحه اصلی را کوتاه و توصیفی بنویسید.
        </li>
        <li class="mb-2">
            <strong>تصویر اشتراک (Open Graph):</strong> اگر بنر اسلایدر دارید، <strong>اولین اسلاید</strong> به‌عنوان تصویر پیش‌نمایش لینک در شبکه‌های اجتماعی استفاده می‌شود؛ در غیر این صورت «تصویر OG پیش‌فرض» همین صفحه.
            برای هر اسلاید فیلد <strong>متن alt</strong> را در تنظیمات صفحه اصلی پر کنید.
        </li>
        <li class="mb-2">
            <strong>داده ساختاریافته (JSON-LD):</strong> به‌صورت خودکار شامل
            <code>WebSite</code>، <code>Organization</code>، <code>WebPage</code>،
            لیست اقامتگاه‌های پیشنهادی، جستجوی سایت و نظرات مهمان (در صورت وجود) است.
        </li>
        <li class="mb-2">
            <strong>اقامتگاه‌های صفحه اصلی:</strong> کارت‌های دسته‌بندی (ارزان، محبوب، جدید، لوکس) در اسکیما به‌عنوان «اقامتگاه‌های پیشنهادی» لیست می‌شوند —
            نام دقیق، کاور باکیفیت و alt تصاویر هر اقامتگاه را در پنل اقامتگاه‌ها رعایت کنید.
        </li>
        <li class="mb-0">
            <strong>کارهای شما بعد از ذخیره:</strong>
            (۱) صفحه را در
            <a href="https://search.google.com/search-console" target="_blank" rel="noopener">Google Search Console</a>
            درخواست ایندکس کنید،
            (۲) با ابزار
            <a href="https://search.google.com/test/rich-results" target="_blank" rel="noopener">Rich Results Test</a>
            JSON-LD را بررسی کنید،
            (۳) لینک صفحه اصلی را در تلگرام/واتساپ تست کنید تا تصویر OG درست نمایش داده شود.
        </li>
    </ul>
